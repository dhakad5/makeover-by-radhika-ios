/* ==========================================================
 *  pdf-export.js  —  Pretty PDFs via jsPDF + AutoTable
 * ========================================================== */

const PDFExport = (() => {

  // Colors (RGB) ----------------------------------------------------------
  const WINE     = [139, 30, 63];
  const ROSEGOLD = [183, 110, 121];
  const GOLD     = [212, 160, 23];
  const BLUSH    = [253, 226, 228];
  const CREAM    = [255, 248, 240];

  // NOTE: jsPDF's default Helvetica only supports WinAnsi encoding, which does NOT
  // include the ₹ rupee symbol (U+20B9). Using it corrupts the surrounding string.
  // We use "Rs." — the standard Indian abbreviation — in PDFs only.
  const inr = n => 'Rs. ' + Number(n || 0).toLocaleString('en-IN');
  const priceCell = p => (p === null || p === undefined || p === '') ? 'Pending' : inr(p);
  const fdate = iso => {
    if (!iso) return '—';
    const d = new Date(iso);
    return isNaN(d) ? iso : d.toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' });
  };

  /** Pretty header band drawn at top of every page. */
  const drawHeader = (doc, title, subtitle = '') => {
    const w = doc.internal.pageSize.getWidth();
    // top band
    doc.setFillColor(...WINE);
    doc.rect(0, 0, w, 26, 'F');
    // gold underline
    doc.setFillColor(...GOLD);
    doc.rect(0, 26, w, 2, 'F');

    doc.setTextColor(255, 248, 240);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(18);
    doc.text('Makeover By Radhika', 14, 12);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.text('Specially for brides & bride to be', 14, 18);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.text(title, w - 14, 14, { align: 'right' });
    if (subtitle) {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.text(subtitle, w - 14, 20, { align: 'right' });
    }
  };

  const drawFooter = (doc) => {
    const pageCount = doc.internal.getNumberOfPages();
    const w = doc.internal.pageSize.getWidth();
    const h = doc.internal.pageSize.getHeight();
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i);
      doc.setDrawColor(...ROSEGOLD);
      doc.setLineWidth(0.3);
      doc.line(14, h - 14, w - 14, h - 14);
      doc.setFontSize(8);
      doc.setTextColor(120);
      doc.text('Generated by Makeover By Radhika • ' + new Date().toLocaleString('en-IN'), 14, h - 8);
      doc.text(`Page ${i} of ${pageCount}`, w - 14, h - 8, { align: 'right' });
    }
  };

  // -----------------------------------------------------------------------
  // 1) Single Client "Price Package" PDF  (Requirement #4)
  // -----------------------------------------------------------------------
  const clientPackage = (client, opts = {}) => {
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF({ unit: 'mm', format: 'a4' });
    const w = doc.internal.pageSize.getWidth();

    drawHeader(doc, 'Price Package', fdate(new Date().toISOString()));

    // Client info card
    let y = 40;
    doc.setFillColor(...BLUSH);
    doc.roundedRect(14, y, w - 28, 30, 3, 3, 'F');
    doc.setTextColor(...WINE);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(15);
    doc.text(client.name, 20, y + 9);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(60);
    doc.text(`Phone:  ${client.phone}`, 20, y + 17);
    doc.text(`Booking For:  ${client.type}`, 20, y + 23);

    const status = Store.clientStatus(client);
    const totals = Store.clientTotals(client);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(...WINE);
    doc.text(`Status: ${status}`, w - 20, y + 9, { align: 'right' });
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(60);
    doc.text(`Advance Paid: ${inr(totals.advance)}`, w - 20, y + 17, { align: 'right' });
    doc.text(`Total Package: ${inr(totals.total)}`, w - 20, y + 23, { align: 'right' });

    // Bookings table
    y += 38;
    const rows = (client.bookings || [])
      .slice().sort(Store.compareByDateAndTiming)
      .map((b, i) => [i + 1, fdate(b.date), b.makeupType, b.timing, b.notes || '—', priceCell(b.price)]);

    if (rows.length === 0) {
      doc.setTextColor(120);
      doc.setFontSize(11);
      doc.text('No bookings recorded yet.', 14, y);
      doc.lastAutoTable = { finalY: y + 4 };  // so service section can position itself
    } else {
      // Section title
      doc.setTextColor(...WINE);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(11);
      doc.text('Makeup Bookings', 14, y);
      doc.autoTable({
        startY: y + 2,
        head: [['#', 'Date', 'Makeup Type', 'Timing', 'Notes', 'Price']],
        body: rows,
        styles: { font: 'helvetica', fontSize: 10, cellPadding: 3 },
        headStyles: { fillColor: WINE, textColor: 255, fontStyle: 'bold' },
        alternateRowStyles: { fillColor: CREAM },
        columnStyles: { 0: { halign: 'center', cellWidth: 10 }, 4: { cellWidth: 'auto' }, 5: { halign: 'right' } },
        margin: { left: 14, right: 14 },
      });
    }

    // ----- Add-On Services (non-date-bound: Facial, Wax, Threading, etc.)
    const services = client.services || [];
    if (services.length > 0) {
      let sy = doc.lastAutoTable.finalY + 8;
      // Page break if needed
      if (sy > 240) { doc.addPage(); sy = 30; }
      doc.setTextColor(...WINE);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(11);
      doc.text('Add-On Services', 14, sy);
      const serviceRows = services.map((s, i) => [
        i + 1, s.name, s.status, s.notes || '—', priceCell(s.price),
      ]);
      doc.autoTable({
        startY: sy + 2,
        head: [['#', 'Service', 'Status', 'Notes', 'Price']],
        body: serviceRows,
        styles: { font: 'helvetica', fontSize: 10, cellPadding: 3 },
        headStyles: { fillColor: ROSEGOLD, textColor: 255, fontStyle: 'bold' },
        alternateRowStyles: { fillColor: CREAM },
        columnStyles: { 0: { halign: 'center', cellWidth: 10 }, 4: { halign: 'right' } },
        margin: { left: 14, right: 14 },
      });
    }

    // ----- Totals box (always, accounts for bookings + services) ---------
    if (rows.length > 0 || services.length > 0) {
      let endY = doc.lastAutoTable.finalY + 6;
      // Gold breakdown box height grows with optional rows.
      let breakdownRows = 2;                                   // Total + Advance always shown
      if (totals.servicesTotal > 0)   breakdownRows += 2;      // Bookings + Services
      if (totals.discount > 0)       breakdownRows += 1;       // Discount
      if (totals.paymentReceived > 0) breakdownRows += 1;      // Payment Received
      const boxH = 4 + breakdownRows * 6;
      const balanceCalloutH = 14;
      const totalH = boxH + 4 + balanceCalloutH;
      if (endY + totalH > 285) { doc.addPage(); endY = 30; }

      // --- Gold breakdown box ---
      doc.setFillColor(...GOLD);
      doc.roundedRect(w - 90, endY, 76, boxH, 2, 2, 'F');
      doc.setTextColor(...WINE);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      let line = endY + 7;
      if (totals.servicesTotal > 0) {
        doc.text('Makeup Bookings:', w - 86, line);
        doc.text(inr(totals.bookingsTotal), w - 18, line, { align: 'right' });
        line += 6;
        doc.text('Services:',     w - 86, line);
        doc.text(inr(totals.servicesTotal), w - 18, line, { align: 'right' });
        line += 6;
      }
      if (totals.discount > 0) {
        doc.text('Discount:',        w - 86, line);
        doc.text('-' + inr(totals.discount), w - 18, line, { align: 'right' });
        line += 6;
      }
      doc.text('Total Package:', w - 86, line);
      doc.text(inr(totals.total), w - 18, line, { align: 'right' });
      line += 6;
      doc.text('Advance Paid:',  w - 86, line);
      doc.text(inr(totals.advance), w - 18, line, { align: 'right' });
      if (totals.paymentReceived > 0) {
        line += 6;
        doc.text('Payment Received:', w - 86, line);
        doc.text(inr(totals.paymentReceived), w - 18, line, { align: 'right' });
      }

      // --- Balance Due callout (separate, bold, BLACK) ---------------------
      const balanceY = endY + boxH + 4;
      doc.setFillColor(255, 255, 255);
      doc.setDrawColor(0, 0, 0);
      doc.setLineWidth(0.8);
      doc.roundedRect(w - 90, balanceY, 76, balanceCalloutH, 2, 2, 'FD');
      doc.setLineWidth(0.2);
      doc.setTextColor(0, 0, 0);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(12);
      doc.text('BALANCE DUE', w - 86, balanceY + 9);
      doc.setFontSize(13);
      doc.text(inr(totals.balance), w - 18, balanceY + 9, { align: 'right' });

      doc.lastAutoTable.finalY = balanceY + balanceCalloutH;
    }

    if (client.notes) {
      const ny = (doc.lastAutoTable?.finalY || y) + 35;
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(9);
      doc.setTextColor(80);
      doc.text(`Notes: ${client.notes}`, 14, ny, { maxWidth: w - 28 });
    }

    drawFooter(doc);
    const filename = `Package_${client.name.replace(/\s+/g, '_')}.pdf`;
    if (NativeIO.isNative()) {
      // WKWebView can't open blob: tabs — hand the PDF to the iOS share sheet (has Quick Look + Save to Files).
      NativeIO.saveBlob(doc.output('blob'), filename);
      return opts.preview ? { filename, opened: true } : filename;
    }
    if (opts.preview) {
      // Open in a new tab for in-browser preview — no download
      const url = URL.createObjectURL(doc.output('blob'));
      const w = window.open(url, '_blank', 'noopener,noreferrer');
      // Revoke after a short delay so the new tab has time to load it
      setTimeout(() => URL.revokeObjectURL(url), 60_000);
      return { url, filename, opened: !!w };
    }
    NativeIO.saveBlob(doc.output('blob'), filename);
    return filename;
  };

  // -----------------------------------------------------------------------
  // 2) All bookings/clients PDF report
  // -----------------------------------------------------------------------
  const allReport = (clients, label = 'All Records') => {
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF({ unit: 'mm', format: 'a4' });
    const w = doc.internal.pageSize.getWidth();
    drawHeader(doc, 'Bookings Report', label);

    let y = 36;

    // Summary
    const totalClients = clients.length;
    let totalBookings = 0, totalServices = 0, totalRevenue = 0, totalAdvance = 0;
    clients.forEach(c => {
      totalBookings += (c.bookings || []).length;
      totalServices += (c.services || []).length;
      const t = Store.clientTotals(c);
      totalRevenue += t.total;
      totalAdvance += t.advance;
    });

    doc.setFillColor(...BLUSH);
    doc.roundedRect(14, y, w - 28, 18, 3, 3, 'F');
    doc.setTextColor(...WINE);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text(`Clients: ${totalClients}`, 18, y + 11);
    doc.text(`Bookings: ${totalBookings}`, 52, y + 11);
    doc.text(`Services: ${totalServices}`, 90, y + 11);
    doc.text(`Revenue: ${inr(totalRevenue)}`, 128, y + 11);
    doc.text(`Advance: ${inr(totalAdvance)}`, 170, y + 11);
    y += 24;

    clients.forEach((c, idx) => {
      const status = Store.clientStatus(c);
      const totals = Store.clientTotals(c);

      // Need page break?
      if (y > 250) { doc.addPage(); drawHeader(doc, 'Bookings Report', label); y = 36; }

      // Client header
      doc.setFillColor(...WINE);
      doc.roundedRect(14, y, w - 28, 9, 2, 2, 'F');
      doc.setTextColor(255);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(11);
      doc.text(`${idx + 1}. ${c.name}   •   ${c.phone}   •   ${c.type}`, 18, y + 6);
      doc.text(`${status}  |  Total ${inr(totals.total)}  |  Adv ${inr(totals.advance)}`, w - 18, y + 6, { align: 'right' });
      y += 12;

      const rows = (c.bookings || [])
        .slice().sort(Store.compareByDateAndTiming)
        .map(b => [fdate(b.date), b.makeupType, b.timing, b.notes || '—', priceCell(b.price)]);

      if (rows.length === 0) {
        doc.setTextColor(120);
        doc.setFont('helvetica', 'italic');
        doc.setFontSize(9);
        doc.text('No bookings.', 18, y + 4);
        y += 8;
      } else {
        doc.autoTable({
          startY: y,
          head: [['Date', 'Makeup Type', 'Timing', 'Notes', 'Price']],
          body: rows,
          styles: { font: 'helvetica', fontSize: 9, cellPadding: 2.5 },
          headStyles: { fillColor: ROSEGOLD, textColor: 255 },
          alternateRowStyles: { fillColor: CREAM },
          columnStyles: { 3: { cellWidth: 'auto' }, 4: { halign: 'right' } },
          margin: { left: 14, right: 14 },
        });
        y = doc.lastAutoTable.finalY + 4;
      }

      // Add-on services per client
      const services = c.services || [];
      if (services.length > 0) {
        if (y > 250) { doc.addPage(); drawHeader(doc, 'Bookings Report', label); y = 36; }
        const sRows = services.map(s => [s.name, s.status, s.notes || '—', priceCell(s.price)]);
        doc.autoTable({
          startY: y,
          head: [['Add-On Service', 'Status', 'Notes', 'Price']],
          body: sRows,
          styles: { font: 'helvetica', fontSize: 9, cellPadding: 2.5 },
          headStyles: { fillColor: GOLD, textColor: WINE, fontStyle: 'bold' },
          alternateRowStyles: { fillColor: CREAM },
          columnStyles: { 3: { halign: 'right' } },
          margin: { left: 14, right: 14 },
        });
        y = doc.lastAutoTable.finalY + 6;
      } else {
        y += 2;
      }
    });

    drawFooter(doc);
    NativeIO.saveBlob(doc.output('blob'), `Makeover_By_Radhika_${new Date().toISOString().slice(0,10)}.pdf`);
  };

  return { clientPackage, allReport };
})();
